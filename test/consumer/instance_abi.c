#include "howl_instance_native.h"
_Static_assert(sizeof(hvt_cell) == 104, "VT scalar record");
_Static_assert(sizeof(hi_service) == 32, "Instance service record");
_Static_assert(HVT_KEY_ENTER == 1 && HVT_KEY_KEYPAD_ENTER == 58, "native key vocabulary");
int howl_external_instance_abi(const uint8_t *font, size_t font_len) {
    hi_instance *instance = 0;
    if (hi_abi_version() != HI_ABI_VERSION) return 1;
    if (hi_create(99, 0, 0, 0, &instance) != HI_VERSION_MISMATCH || instance) return 2;
    if (hi_send_named_key(0, HVT_KEY_ENTER, HVT_PRESS, 0) != HI_INVALID_ARGUMENT) return 3;
    if (hi_destroy(&instance) != HI_OK || instance) return 4;
    hi_presentation *presentation = 0;
    hi_cell_size cell = {1,2,3};
    if (hi_presentation_create(99,0,&presentation) != HI_VERSION_MISMATCH || presentation) return 5;
    if (hi_presentation_cell_size(0,&cell) != HI_INVALID_ARGUMENT || cell.width || cell.height || cell.reserved) return 6;
    if (hi_presentation_release(&presentation) != HI_OK || presentation) return 8;
    hvt_observation *observation = 0;
    if (hi_observation_open(HI_ABI_VERSION,0,&observation) != HI_INVALID_ARGUMENT || observation) return 9;
    hi_presentation_config fonts = {0};
    fonts.fonts[0].kind = HI_FONT_PATH;
    fonts.fonts[0].primary = (hi_bytes){font, font_len};
    fonts.pixel_size = 18;
    fonts.max_sequence_scalars = 16;
    fonts.shape_entries = 256; fonts.shape_scalars = 1024; fonts.shape_glyphs = 1024;
    fonts.shaped_capacity = 1024; fonts.raster_bytes = 65536;
    if (hi_presentation_create(HI_ABI_VERSION,&fonts,&presentation) != HI_OK) return 10;
    const char shell[] = "/bin/sh", command[] = "exit 0";
    hi_launch launch = {{(const uint8_t *)shell,sizeof(shell)-1},
        {(const uint8_t *)command,sizeof(command)-1},{0,0},0,0,3,12,8,0};
    hi_instance_config config = {0};
    config.stroke_points[0] = 0.001f; config.stroke_points[1] = 1;
    config.stroke_points[2] = 1.5f; config.stroke_points[3] = 2;
    config.dpi_x_numerator = 96; config.dpi_y_numerator = 96;
    config.dpi_x_denominator = 1; config.dpi_y_denominator = 1;
    config.atlas_width = 256; config.atlas_height = 256; config.atlas_entries = 256;
    config.command_capacity = 4; config.command_limit = 4096;
    if (hi_create(HI_ABI_VERSION,&launch,presentation,&config,&instance) != HI_OK) return 11;
    if (hi_presentation_release(&presentation) != HI_OK || presentation) return 12;
    hi_frame_stream *stream = 0;
    hi_frame_info frame = {0};
    if (hi_frame_open(HI_ABI_VERSION,instance,&stream) != HI_OK) return 13;
    if (hi_publish_frame(instance,0) != HI_OK) return 14;
    if (hi_frame_acquire(stream,&frame) != HI_OK || !frame.cell_width || !frame.cell_height) return 15;
    if (hi_destroy(&instance) != HI_BUSY || !instance) return 16;
    if (hi_frame_abandon(stream) != HI_OK) return 17;
    hi_frame_close(&stream);
    if (stream || hi_destroy(&instance) != HI_OK || instance) return 18;
    return 0;
}
_Static_assert(_Alignof(hvt_cell) == _Alignof(uint32_t), "VT cell alignment");
_Static_assert(offsetof(hvt_cell, scalar_count) == 96, "VT scalar count offset");
_Static_assert(offsetof(hvt_cell, x) == 99 && offsetof(hvt_cell, y) == 100, "VT lead offsets");
_Static_assert(offsetof(hi_service, descriptor) == 8 && offsetof(hi_service, changed) == 16, "service header");
_Static_assert(offsetof(hi_service, sync_trailing_effect) == 25, "service sync facts");
_Static_assert(offsetof(hi_service, reserved) == 28, "service initialized tail");
_Static_assert(sizeof(hi_launch) == 4 * sizeof(hi_bytes) + 8, "launch layout");
_Static_assert(offsetof(hi_launch, rows) == 4 * sizeof(hi_bytes), "launch dimensions");

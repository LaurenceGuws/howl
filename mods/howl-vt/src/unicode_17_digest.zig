//! Owns the package check/test integrity gate for generated Unicode 17 properties.

const std = @import("std");

const properties = @embedFile("unicode_17.bin");
const graphemes = @embedFile("unicode_17_graphemes.bin");

const properties_digest = [32]u8{
    0x4c, 0x17, 0xc8, 0xd6, 0x9e, 0x8b, 0xbb, 0xcf,
    0x06, 0x91, 0xb5, 0xaf, 0xa0, 0xb3, 0x01, 0x23,
    0x9e, 0x10, 0xf4, 0x8e, 0xe2, 0xb1, 0x6c, 0x4a,
    0xc9, 0x40, 0x4a, 0x76, 0xd9, 0x51, 0xa7, 0xb1,
};
const graphemes_digest = [32]u8{
    0xda, 0xfc, 0xf2, 0xee, 0x3f, 0x3c, 0x60, 0xf7,
    0x53, 0xe8, 0x2f, 0x96, 0x76, 0xba, 0xe5, 0x11,
    0x6a, 0x15, 0x21, 0x8a, 0x7b, 0xac, 0xdc, 0x63,
    0xca, 0x1d, 0xfa, 0x37, 0xce, 0x0b, 0x84, 0x6d,
};

/// Rejects generated Unicode 17 runtime or conformance drift.
pub fn main() error{GeneratedUnicodeDrift}!void {
    var actual: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(properties, &actual, .{});
    if (!std.mem.eql(u8, &actual, &properties_digest))
        return error.GeneratedUnicodeDrift;
    std.crypto.hash.sha2.Sha256.hash(graphemes, &actual, .{});
    if (!std.mem.eql(u8, &actual, &graphemes_digest))
        return error.GeneratedUnicodeDrift;
}
